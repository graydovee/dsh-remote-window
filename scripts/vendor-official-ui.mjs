/**
 * Vendor the official Conversation/Chat UI stylesheet layer into this plugin.
 *
 * WHY: our server-mode main area must look and behave like the official DSH
 * shell. Re-drawing the CSS by hand drifted from the shell (missing composer
 * rules, stale hashed class names after a DSH upgrade). This script copies the
 * official CSS-module bodies for the shell surfaces we mount and rewrites their
 * local class names to stable, collision-safe names.
 *
 * WHAT IT DOES:
 *   1. copies the official CSS modules for the conversation skeleton and chat
 *      message layer;
 *   2. prefixes every local class selector with a module-specific prefix while
 *      leaving `:global(...)` selectors alone;
 *   3. emits `classnames.ts` (name maps) and `styles.ts` (one injected string).
 *
 * The copied CSS is byte-faithful apart from the local-class prefix. Official
 * class names, comments, selectors, tokens and keyframes stay verbatim.
 *
 * Usage (re-run after every DSH upgrade; the output is committed):
 *   node scripts/vendor-official-ui.mjs [--dsh <checkout>] [--source-label <label>]
 *
 * Never write a machine-specific absolute path into the committed NOTICE.
 */
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pluginRoot = resolve(here, '..')
const outDir = join(pluginRoot, 'src', 'client', 'vendor', 'official-ui')

const dshArgIndex = process.argv.indexOf('--dsh')
const dshRoot = resolve(
  dshArgIndex === -1
    ? join(process.env['HOME'] ?? '', 'Desktop/project/deepseek-harness')
    : process.argv[dshArgIndex + 1],
)

function gitFact(...args) {
  try {
    return execFileSync('git', ['-C', dshRoot, ...args], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim()
  } catch {
    return undefined
  }
}

const labelIndex = process.argv.indexOf('--source-label')
const sourceLabel = (labelIndex === -1 ? undefined : process.argv[labelIndex + 1])
  ?? (() => {
    const tag = gitFact('describe', '--tags', '--exact-match')
    const commit = gitFact('rev-parse', '--short=10', 'HEAD')
    if (tag !== undefined && commit !== undefined) return `${tag} (commit ${commit})`
    if (commit !== undefined) return `commit ${commit}`
    return undefined
  })()
  ?? '<dsh-checkout>'

