/**
 * Vendor the official workspace row layer into this plugin.
 *
 * WHY: the plugin must render remote workspaces/sessions with the *official*
 * rows — same markup, same CSS, same interactions — instead of a hand-drawn
 * lookalike. The official module factorizes exactly that: `rows/Rows.tsx`
 * exports two pure, prop-driven components (`ProjectRowItem` for a
 * workspace/group row, `SessionNodeItem` for a session row) plus their CSS
 * modules. The browser shell above them (`WorkspaceBrowser.tsx`) is NOT usable
 * here: it hard-codes the two-level "workspace → session" walk, while this
 * plugin needs three levels (connection → workspace → session).
 *
 * WHAT IT DOES: copies those files out of a DSH checkout and rewrites the three
 * things a foreign bundle cannot keep as-is:
 *   1. the CSS-module imports (this build has no CSS pipeline) → a class map,
 *      with every class name prefixed so the vendored rules cannot collide with
 *      the shell's own copies of the same modules;
 *   2. the `@deepseek-ai/dsh-util-workspace-path` import → our local copy;
 *   3. type-only imports that point at shell-internal modules → `./models.ts`.
 *
 * Usage (re-run after a shell upgrade; the output is committed):
 *   node scripts/vendor-workspace-rows.mjs [--dsh <checkout>]
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pluginRoot = resolve(here, '..')
const outDir = join(pluginRoot, 'src', 'client', 'vendor', 'workspace-rows', 'generated')

const dshArgIndex = process.argv.indexOf('--dsh')
const dshRoot = resolve(
  dshArgIndex === -1 ? join(process.env['HOME'] ?? '', 'Desktop/project/deepseek-harness') : process.argv[dshArgIndex + 1],
)
const uiWorkspace = join(dshRoot, 'packages', 'client', 'ui-workspace', 'src', 'client')

/** Prefix for the vendored rows module classes. */
const ROWS_PREFIX = 'dsh-rwv-rows-'
/** Prefix for the vendored animated-rows module classes. */
const ANIM_PREFIX = 'dsh-rwv-anim-'

/** Read one vendored source file. */
function read(relative) {
  return readFileSync(join(uiWorkspace, relative), 'utf8')
}

/**
 * Rewrite every class selector with one module prefix.
 * @param css - CSS module source.
 * @param prefix - replacement prefix for the leading dot.
 * @returns the rewritten CSS plus the class-name map it used.
 */
function prefixClasses(css, prefix) {
  const names = new Map()
  const out = css.replace(/\.([A-Za-z_][A-Za-z0-9_-]*)/g, (_match, name) => {
    names.set(name, `${prefix}${name}`)
    return `.${prefix}${name}`
  })
  return { css: out, names }
}

/** Provenance header prepended to every generated file. */
const header = (source) => `/**
 * GENERATED by scripts/vendor-workspace-rows.mjs — do not edit by hand.
 * Source: ${source}
 * Re-run the script after a DSH upgrade; see ../NOTICE.md.
 */
`

/** Escape the two sequences that would end or interpolate a template literal. */
function escapeForTemplate(text) {
  return text.replace(/`/g, '\\`').replace(/\$\{/g, '\\${')
}

const rowsTsx = read('rows/Rows.tsx')
const animTsx = read('rows/AnimatedRows.tsx')
const rowsCss = prefixClasses(read('rows/Rows.module.css'), ROWS_PREFIX)
const animCss = prefixClasses(read('rows/AnimatedRows.module.css'), ANIM_PREFIX)

/** Swap the CSS-module import for the generated class map. */
function rewireCss(source, importName, exportName) {
  return source.replace(
    /import css from '\.\/[A-Za-z]+\.module\.css'/,
    `import { ${exportName} as css } from './classnames.ts'`,
  ).replace(/import css from '\.\/[A-Za-z]+\.module\.css'/g, `import { ${exportName} as css } from './classnames.ts'`)
}

/** Point shell-internal type imports at the vendored type module. */
function rewireTypes(source) {
  return source
    .replace(/from '@deepseek-ai\/dsh-util-workspace-path'/g, "from '../home-path.ts'")
    .replace(/from '@deepseek-ai\/dsh-client-shortcuts\/client'/g, "from '../models.ts'")
    .replace(/from '\.\.\/contract\/slots\.ts'/g, "from '../models.ts'")
    .replace(/from '\.\.\/tree\.ts'/g, "from '../models.ts'")
    .replace(/WorkspaceBrowserProps\['t'\]/g, 'RowsTranslate')
    .replace(/WorkspaceBrowserProps\['useSessions'\]/g, 'unknown')
    .replace(/\bWorkspaceBrowserProps\b/g, 'RowsProps')
}

/**
 * Verbatim upstream bodies are not re-typed for this repo's tsconfig: upstream
 * compiles them under the shell's own JSX/React settings. `@ts-nocheck` keeps
 * the copy byte-faithful (that is the point of vendoring) while the *props*
 * are still declared, so every call site in this plugin stays type-checked.
 */
const nocheck = '// @ts-nocheck -- vendored verbatim; props remain typed for our call sites\n'

const generated = {
  'Rows.tsx': header('packages/client/ui-workspace/src/client/rows/Rows.tsx')
    + nocheck
    + rewireTypes(rewireCss(rowsTsx, 'rowsCss', 'rowsCss')),
  'AnimatedRows.tsx': header('packages/client/ui-workspace/src/client/rows/AnimatedRows.tsx')
    + nocheck
    + rewireCss(animTsx, 'animateCss', 'animateCss'),
  'classnames.ts': header('…/rows/Rows.module.css + AnimatedRows.module.css')
    + `/* Class maps for the two vendored CSS modules (names are prefixed at vendor time). */\n`
    + `export const rowsCss = ${JSON.stringify(Object.fromEntries(rowsCss.names), null, 2)} as const\n\n`
    + `export const animateCss = ${JSON.stringify(Object.fromEntries(animCss.names), null, 2)} as const\n`,
  'row-styles.ts': header('…/rows/Rows.module.css + AnimatedRows.module.css')
    + `/* One stylesheet for both modules; injected by the plugin's existing <style> element. */\n`
    // The CSS carries prose comments; escape the two sequences a template
    // literal would otherwise act on (` and ${) rather than editing the copy.
    + `export const ROW_STYLES = String.raw\`\n${escapeForTemplate(rowsCss.css)}\n${escapeForTemplate(animCss.css)}\n\`\n`,
  'locales.ts': header('packages/client/ui-workspace/src/client/locales.ts')
    + '/* The `workspace` namespace dictionaries, copied whole: the vendored rows\n'
    + '   translate through them, so their wording cannot drift from the shell. */\n'
    + read('locales.ts')
      // The key-union type is shell-internal; the dictionaries are typed loosely
      // here so both keep their exact `satisfies` shape after the rewrite.
      .replace('satisfies Record<WorkspaceKey, string>', 'satisfies Record<string, string>')
      .replace(/\/\*\* The workspace namespace key union\. \*\/\nexport type WorkspaceKey = keyof typeof zh\n/, '')
      .replace(/^export const en = \{/m, 'export const en: Record<string, string> = {'),
}

mkdirSync(outDir, { recursive: true })
for (const [name, content] of Object.entries(generated)) {
  writeFileSync(join(outDir, name), content)
  process.stdout.write(`wrote ${name} (${content.length} bytes)\n`)
}

writeFileSync(join(dirname(outDir), 'NOTICE.md'), `# Vendored: the official workspace row layer

Source checkout: \`${dshRoot}\`
Upstream paths:

- \`packages/client/ui-workspace/src/client/rows/Rows.tsx\`
- \`packages/client/ui-workspace/src/client/rows/AnimatedRows.tsx\`
- \`packages/client/ui-workspace/src/client/rows/Rows.module.css\`
- \`packages/client/ui-workspace/src/client/rows/AnimatedRows.module.css\`
- \`packages/client/ui-workspace/src/client/locales.ts\` (the \`workspace\` namespace dictionaries)

License: MIT (DeepSeek Harness). Files under \`generated/\` are produced by
\`scripts/vendor-workspace-rows.mjs\`, which prefixes every CSS class
(\`${ROWS_PREFIX}\` / \`${ANIM_PREFIX}\`) and rewires the imports this bundle cannot
keep. Do not edit them by hand — re-run the script after upgrading DSH.
`)
process.stdout.write('wrote NOTICE.md\n')
